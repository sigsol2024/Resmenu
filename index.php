    <script>
        // Pricing Toggle
        document.addEventListener('DOMContentLoaded', function() {
            const switchEl = document.getElementById('pricingSwitch');
            const prices = document.querySelectorAll('.pricing-price');
            let isAnnual = false;
            
            if (switchEl) {
                switchEl.addEventListener('click', function() {
                    isAnnual = !isAnnual;
                    switchEl.classList.toggle('active');
                    
                    prices.forEach(function(priceEl) {
                        const monthly = priceEl.getAttribute('data-monthly');
                        const annual = priceEl.getAttribute('data-annual');
                        
                        if (isAnnual && annual) {
                            priceEl.textContent = annual;
                        } else if (!isAnnual && monthly) {
                            priceEl.textContent = monthly;
                        }
                    });
                });
            }
            
            // Scroll animations
            const observerOptions = {
                threshold: 0.1,
                rootMargin: '0px 0px -50px 0px'
            };
            
            const observer = new IntersectionObserver(function(entries) {
                entries.forEach(function(entry) {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('visible');
                    }
                });
            }, observerOptions);
            
            // Observe all scroll-fade-in elements
            document.querySelectorAll('.scroll-fade-in').forEach(function(el) {
                observer.observe(el);
            });
        });
    </script>
